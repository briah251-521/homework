// ==========================================
// Завдання 1.1: Площа кола
// ==========================================
let radius = 5; // Можеш змінити значення радіуса на своє
let circleArea = Math.PI * Math.pow(radius, 2);
console.log(`Завдання 1.1: Площа кола з радіусом ${radius} дорівнює ${circleArea.toFixed(2)}`);

// ==========================================
// Завдання 1.2: Площа прямокутника
// ==========================================
let length = 10; // Довжина прямокутника
let width = 4.5; // Ширина прямокутника
let rectangleArea = length * width;
console.log(`Завдання 1.2: Площа прямокутника (довжина: ${length}, ширина: ${width}) дорівнює ${rectangleArea.toFixed(2)}`);

// ==========================================
// Завдання 1.3: Об'єм циліндра
// ==========================================
let radiusCylinder = 3; // Радіус основи циліндра
let height = 7;         // Висота циліндра
let cylinderVolume = Math.PI * Math.pow(radiusCylinder, 2) * height;
console.log(`Завдання 1.3: Об'єм циліндра (радіус: ${radiusCylinder}, висота: ${height}) дорівнює ${cylinderVolume.toFixed(2)}`); 